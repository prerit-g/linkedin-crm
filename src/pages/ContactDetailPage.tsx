import React, { useState, useEffect, useCallback } from 'react';
import { useNavigate, useParams } from 'react-router-dom';
import toast from 'react-hot-toast';
import { Button } from '../components/ui/Button';
import { Card, CardContent, CardHeader, CardTitle } from '../components/ui/Card';
import { StatusPill } from '../components/ui/StatusPill';
import { CategoryBadge } from '../components/ui/CategoryBadge';
import { ConfidenceBadge } from '../components/ui/ConfidenceBadge';
import { Input } from '../components/ui/Input';
import { Textarea } from '../components/ui/Textarea';
import { ArrowLeft, Copy, RefreshCw, CheckCircle, ExternalLink, User, Calendar, MessageSquare } from 'lucide-react';
import { useContacts } from '../hooks/useContacts';
import { useContactById } from '../hooks/useContacts';
import { openLinkedInProfile, getLinkedInManualActionReminder } from '../utils/linkedin';
import { safeCopyToClipboard } from '../utils/clipboard';
import { ContactStatus, ResponseStatus, STATUS_LABELS, RESPONSE_STATUS_LABELS } from '../types/contact';
import { format } from 'date-fns';

const ContactDetailPage: React.FC = () => {
  const { id } = useParams();
  const navigate = useNavigate();
  const { updateContact } = useContacts();
  const contact = useContactById(id || '');
  const [notes, setNotes] = useState(contact?.userNotes || '');
  const [isSaving, setIsSaving] = useState(false);
  const [trackingStatus, setTrackingStatus] = useState<ContactStatus>(contact?.status || 'NEW');
  const [responseStatus, setResponseStatus] = useState<ResponseStatus>(contact?.responseStatus || 'NONE');
  const [followUpDate, setFollowUpDate] = useState(contact?.followUpDate || '');
  const [contactedDate, setContactedDate] = useState(contact?.contactedDate || '');
  const [isSavingTracking, setIsSavingTracking] = useState(false);
  
  // Debounced notes save
  const debouncedSaveNotes = useCallback(() => {
    if (notes !== contact?.userNotes) {
      setIsSaving(true);
      updateContact(contact.id, { userNotes: notes })
        .then(() => {
          // Success - don't show toast for auto-save
        })
        .catch(() => toast.error('Failed to save notes'))
        .finally(() => setIsSaving(false));
    }
  }, [notes, contact, updateContact]);

  // Handle loading state
  if (!contact) {
    return (
      <div className="flex items-center justify-center h-64">
        <div className="text-center">
          <h2 className="text-xl font-semibold text-gray-700">Contact not found</h2>
          <p className="text-sm text-gray-400 mt-1">The contact you're looking for doesn't exist.</p>
          <Button
            variant="ghost"
            onClick={() => navigate('/contacts')}
            className="mt-4"
          >
            <ArrowLeft className="mr-2 h-4 w-4" />
            Back to Contacts
          </Button>
        </div>
      </div>
    );
  }

  // Message template (will be generated by classification engine in Phase 3)
  const messageTemplate = contact.generatedMessage || 
    `Hi ${contact.firstName},\n\nI see you're working in ${contact.function} at ${contact.company}. I am actively looking for an entry-level role in this space.\n\nTo prepare, I built a hands-on AP project on my profile using PostgreSQL, Excel, and Power BI to manage data pipelines and track vendor metrics. If your team has any junior openings or an internal referral program, I would love the opportunity to share my resume.`;

  // Initialize tracking state when contact changes
  useEffect(() => {
    if (contact) {
      setTrackingStatus(contact.status);
      setResponseStatus(contact.responseStatus || 'NONE');
      setFollowUpDate(contact.followUpDate || '');
      setContactedDate(contact.contactedDate || '');
      setNotes(contact.userNotes || '');
    }
  }, [contact]);

  const handleCopyMessage = async () => {
    await safeCopyToClipboard(
      messageTemplate,
      () => toast.success('Message copied to clipboard'),
      (error) => toast.error(`Failed to copy: ${error}`)
    );
  };

  const handleOpenLinkedIn = () => {
    try {
      openLinkedInProfile(contact.linkedInUrl);
      toast(getLinkedInManualActionReminder(), {
        duration: 6000,
        icon: '🔗',
      });
    } catch (error) {
      console.error('Error opening LinkedIn:', error);
      toast.error('Invalid LinkedIn URL. Please check the URL and try again.');
    }
  };

  const handleApproveMessage = () => {
    updateContact(contact.id, { 
      status: 'APPROVED',
      messageStatus: 'APPROVED' as const
    });
    toast.success('Message approved');
  };

  const handleMarkContacted = () => {
    updateContact(contact.id, { 
      status: 'CONTACTED',
      contactedDate: new Date().toISOString().split('T')[0]
    });
    toast.success('Marked as contacted');
  };

  const handleSaveNotes = () => {
    setIsSaving(true);
    updateContact(contact.id, { userNotes: notes })
      .then(() => toast.success('Notes saved'))
      .catch(() => toast.error('Failed to save notes'))
      .finally(() => setIsSaving(false));
  };

  const handleStatusChange = (newStatus: ContactStatus) => {
    setTrackingStatus(newStatus);
    
    // Automatic behavior based on status
    const updates: Record<string, any> = { status: newStatus };
    
    if (newStatus === 'CONTACTED' && !contactedDate) {
      const today = new Date().toISOString().split('T')[0];
      setContactedDate(today);
      updates.contactedDate = today;
    }
    
    // Save immediately when status changes
    saveTrackingUpdates(updates);
  };

  const handleResponseStatusChange = (newResponseStatus: ResponseStatus) => {
    setResponseStatus(newResponseStatus);
    // Auto-save when response status changes
    saveTrackingUpdates({ responseStatus: newResponseStatus });
  };

  const handleFollowUpDateChange = (date: string) => {
    setFollowUpDate(date);
    // Auto-save when follow-up date changes
    saveTrackingUpdates({ followUpDate: date });
  };

  const handleSaveTracking = () => {
    const updates: Record<string, any> = {
      status: trackingStatus,
      responseStatus,
      followUpDate,
      contactedDate,
    };
    
    // Additional automatic behavior
    if (trackingStatus === 'CONTACTED' && !contactedDate) {
      const today = new Date().toISOString().split('T')[0];
      updates.contactedDate = today;
      setContactedDate(today);
    }
    
    saveTrackingUpdates(updates);
  };

  const saveTrackingUpdates = (updates: Record<string, any>) => {
    setIsSavingTracking(true);
    updateContact(contact.id, updates)
      .then(() => {
        toast.success('Tracking updated');
      })
      .catch((error) => {
        console.error('Error updating tracking:', error);
        toast.error('Failed to update tracking');
      })
      .finally(() => setIsSavingTracking(false));
  };

  // Format date for display
  const formatDate = (dateString: string) => {
    if (!dateString) return 'Not set';
    try {
      return format(new Date(dateString), 'MMM d, yyyy');
    } catch {
      return dateString;
    }
  };

  // Get relative time for last updated
  const getRelativeTime = (dateString: string) => {
    if (!dateString) return 'Just now';
    try {
      const date = new Date(dateString);
      const now = new Date();
      const diffMs = now.getTime() - date.getTime();
      const diffMins = Math.floor(diffMs / (1000 * 60));
      const diffHours = Math.floor(diffMs / (1000 * 60 * 60));
      const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));
      
      if (diffMins < 1) return 'Just now';
      if (diffMins < 60) return `${diffMins} minute${diffMins !== 1 ? 's' : ''} ago`;
      if (diffHours < 24) return `${diffHours} hour${diffHours !== 1 ? 's' : ''} ago`;
      if (diffDays < 7) return `${diffDays} day${diffDays !== 1 ? 's' : ''} ago`;
      return format(date, 'MMM d, yyyy');
    } catch {
      return dateString;
    }
  };

  return (
    <div>
      <div className="mb-6">
        <Button
          variant="ghost"
          onClick={() => navigate('/contacts')}
          className="mb-4"
        >
          <ArrowLeft className="mr-2 h-4 w-4" />
          Back to Contacts
        </Button>
        
        <div className="flex items-start justify-between">
          <div>
            <h1 className="text-2xl font-bold text-gray-900">
              {contact.firstName} {contact.lastName}
            </h1>
            <p className="mt-1 text-sm text-gray-600">
              {contact.currentJobTitle} at {contact.company}
            </p>
          </div>
          <div className="flex items-center gap-2">
            <StatusPill status={contact.status} />
          </div>
        </div>
      </div>

      <div className="grid gap-6 lg:grid-cols-3">
        {/* Left column */}
        <div className="lg:col-span-2 space-y-6">
          {/* Profile Card */}
          <Card>
            <CardHeader>
              <CardTitle>Profile</CardTitle>
            </CardHeader>
            <CardContent>
              <div className="grid gap-4 sm:grid-cols-2">
                <Input 
                  label="Name" 
                  value={`${contact.firstName} ${contact.lastName}`} 
                  readOnly 
                />
                <Input 
                  label="Role" 
                  value={contact.currentJobTitle} 
                  readOnly 
                />
                <Input 
                  label="Company" 
                  value={contact.company} 
                  readOnly 
                />
                <Input 
                  label="Function" 
                  value={contact.function} 
                  readOnly 
                />
                <Input 
                  label="Seniority" 
                  value={contact.seniority} 
                  readOnly 
                />
                <Input 
                  label="LinkedIn URL" 
                  value={contact.linkedInUrl} 
                  readOnly 
                />
              </div>
            </CardContent>
          </Card>

          {/* Classification Card */}
          <Card>
            <CardHeader>
              <CardTitle>Classification</CardTitle>
            </CardHeader>
            <CardContent>
              <div className="space-y-4">
                <div className="flex items-center gap-4">
                  <div>
                    <p className="text-sm font-medium text-gray-700">Category</p>
                    <div className="mt-1">
                      <CategoryBadge category={contact.category} />
                    </div>
                  </div>
                  <div>
                    <p className="text-sm font-medium text-gray-700">Confidence</p>
                    <div className="mt-1">
                      <ConfidenceBadge confidence={contact.confidence} />
                    </div>
                  </div>
                </div>
                <Textarea
                  label="Reason"
                  value={contact.classificationReason}
                  readOnly
                  rows={2}
                />
                <div className="text-sm">
                  <p className="font-medium text-gray-700">Relevance:</p>
                  <p className="text-gray-600">
                    {contact.isRelevant ? 'Relevant for outreach' : 'Not relevant'}
                  </p>
                </div>
              </div>
            </CardContent>
          </Card>

          {/* Message Card */}
          <Card>
            <CardHeader>
              <CardTitle>Message</CardTitle>
            </CardHeader>
            <CardContent>
              <div className="space-y-4">
                <Textarea
                  value={messageTemplate}
                  readOnly
                  rows={6}
                />
                <div className="flex flex-wrap gap-2">
                  <Button 
                    variant="outline" 
                    size="sm"
                    onClick={handleCopyMessage}
                  >
                    <Copy className="mr-2 h-4 w-4" />
                    Copy Message
                  </Button>
                  <Button variant="outline" size="sm">
                    <RefreshCw className="mr-2 h-4 w-4" />
                    Regenerate
                  </Button>
                  {contact.status === 'MESSAGE_READY' && (
                    <Button 
                      variant="primary" 
                      size="sm"
                      onClick={handleApproveMessage}
                    >
                      <CheckCircle className="mr-2 h-4 w-4" />
                      Approve Message
                    </Button>
                  )}
                </div>
              </div>
            </CardContent>
          </Card>
        </div>

        {/* Right column */}
        <div className="space-y-6">
          {/* LinkedIn Card */}
          <Card>
            <CardHeader>
              <CardTitle>LinkedIn</CardTitle>
            </CardHeader>
            <CardContent>
              <div className="space-y-4">
                <p className="text-sm text-gray-600">
                  Open LinkedIn to manually send your message.
                </p>
                <Button 
                  variant="primary" 
                  className="w-full"
                  onClick={handleOpenLinkedIn}
                >
                  <ExternalLink className="mr-2 h-4 w-4" />
                  Open LinkedIn
                </Button>
                <div className="rounded-md bg-amber-50 p-3 text-sm text-amber-800">
                  <p className="font-medium">Manual Action Required</p>
                  <p className="mt-1 whitespace-pre-line">
                    {getLinkedInManualActionReminder()}
                  </p>
                </div>
              </div>
            </CardContent>
          </Card>

          {/* Tracking Card */}
          <Card>
            <CardHeader>
              <CardTitle>Tracking</CardTitle>
            </CardHeader>
            <CardContent>
              <div className="space-y-4">
                {/* Status Selector */}
                <div>
                  <label className="text-sm font-medium text-gray-700 block mb-1">
                    Status
                  </label>
                  <select
                    className="w-full rounded-md border border-gray-300 bg-white px-3 py-2 text-sm focus:border-indigo-500 focus:outline-none focus:ring-2 focus:ring-indigo-200"
                    value={trackingStatus}
                    onChange={(e) => handleStatusChange(e.target.value as ContactStatus)}
                  >
                    {Object.entries(STATUS_LABELS).map(([value, label]) => (
                      <option key={value} value={value}>
                        {label}
                      </option>
                    ))}
                  </select>
                </div>

                {/* Contacted Date */}
                <div>
                  <label className="text-sm font-medium text-gray-700 block mb-1">
                    Contacted Date
                  </label>
                  <div className="flex items-center">
                    <Calendar className="h-4 w-4 text-gray-400 mr-2" />
                    <input
                      type="date"
                      className="flex-1 rounded-md border border-gray-300 bg-white px-3 py-2 text-sm focus:border-indigo-500 focus:outline-none focus:ring-2 focus:ring-indigo-200"
                      value={contactedDate}
                      onChange={(e) => {
                        setContactedDate(e.target.value);
                        saveTrackingUpdates({ contactedDate: e.target.value });
                      }}
                      disabled={trackingStatus !== 'CONTACTED' && trackingStatus !== 'REPLIED' && trackingStatus !== 'NO_RESPONSE'}
                    />
                  </div>
                  {!contactedDate && trackingStatus === 'CONTACTED' && (
                    <p className="mt-1 text-xs text-amber-600">
                      Auto-filled with today's date
                    </p>
                  )}
                </div>

                {/* Response Status - shown when REPLIED or other relevant statuses */}
                {(trackingStatus === 'REPLIED' || trackingStatus === 'NO_RESPONSE' || trackingStatus === 'FOLLOW_UP') && (
                  <div>
                    <label className="text-sm font-medium text-gray-700 block mb-1">
                      Response Status
                    </label>
                    <div className="flex items-center">
                      <MessageSquare className="h-4 w-4 text-gray-400 mr-2" />
                      <select
                        className="flex-1 rounded-md border border-gray-300 bg-white px-3 py-2 text-sm focus:border-indigo-500 focus:outline-none focus:ring-2 focus:ring-indigo-200"
                        value={responseStatus}
                        onChange={(e) => handleResponseStatusChange(e.target.value as ResponseStatus)}
                      >
                        {Object.entries(RESPONSE_STATUS_LABELS).map(([value, label]) => (
                          <option key={value} value={value}>
                            {label}
                          </option>
                        ))}
                      </select>
                    </div>
                    {responseStatus === 'POSITIVE' && (
                      <p className="mt-1 text-xs text-green-600">
                        Great! Congratulations on the positive response.
                      </p>
                    )}
                  </div>
                )}

                {/* Follow-Up Date - shown when FOLLOW_UP or CONTACTED */}
                {(trackingStatus === 'FOLLOW_UP' || trackingStatus === 'CONTACTED') && (
                  <div>
                    <label className="text-sm font-medium text-gray-700 block mb-1">
                      Follow-Up Date
                    </label>
                    <div className="flex items-center">
                      <Calendar className="h-4 w-4 text-gray-400 mr-2" />
                      <input
                        type="date"
                        className="flex-1 rounded-md border border-gray-300 bg-white px-3 py-2 text-sm focus:border-indigo-500 focus:outline-none focus:ring-2 focus:ring-indigo-200"
                        value={followUpDate}
                        onChange={(e) => handleFollowUpDateChange(e.target.value)}
                        min={new Date().toISOString().split('T')[0]}
                      />
                    </div>
                    {followUpDate && new Date(followUpDate) < new Date() && (
                      <p className="mt-1 text-xs text-amber-600">
                        Follow-up date is in the past
                      </p>
                    )}
                  </div>
                )}

                {/* Notes with auto-save */}
                <div>
                  <label className="text-sm font-medium text-gray-700 block mb-1">
                    Notes
                  </label>
                  <Textarea
                    value={notes}
                    onChange={(e) => setNotes(e.target.value)}
                    onBlur={debouncedSaveNotes}
                    rows={3}
                    placeholder="Add notes about this contact..."
                    className="w-full"
                  />
                  <div className="mt-1 flex justify-between items-center">
                    <span className="text-xs text-gray-500">
                      Auto-saves when you click away
                    </span>
                    {isSaving && (
                      <span className="text-xs text-gray-500">
                        Saving...
                      </span>
                    )}
                  </div>
                </div>

                {/* Last Updated */}
                <div className="pt-2 border-t border-gray-200">
                  <p className="text-sm text-gray-500">
                    Last updated: {getRelativeTime(contact.lastUpdated)}
                  </p>
                </div>

                {/* Save Tracking Button */}
                <Button 
                  variant="outline" 
                  className="w-full"
                  onClick={handleSaveTracking}
                  isLoading={isSavingTracking}
                >
                  Save Tracking Changes
                </Button>
              </div>
            </CardContent>
          </Card>
        </div>
      </div>
    </div>
  );
};

export default ContactDetailPage;